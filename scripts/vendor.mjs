// Downloads the third-party files the app uses into vendor/ (Google Fonts and the
// mp4/webm muxers), so the desktop app works fully offline. Run when the lists below
// change (needs internet): `bun run vendor`. The results are committed.
import { createHash } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = join(root, "vendor");
const fontsDir = join(vendor, "fonts");

// Google Fonts families (css2 API syntax). The app's UI uses Geist; the rest are text-layer fonts.
const FONTS = [
  "Geist:wght@300;400;500;600;700",
  "Caveat:wght@400;600;700",
  "DM+Sans:wght@300;400;500;600",
  "Patrick+Hand",
  "Permanent+Marker",
  "Roboto:wght@400;700",
  "Merriweather:wght@400;700",
  "Space+Mono",
  "Nunito:wght@400;700",
];

const SCRIPTS = {
  "mp4-muxer.mjs": "https://cdn.jsdelivr.net/npm/mp4-muxer@5.2.2/build/mp4-muxer.mjs",
  // Same author and API as mp4-muxer: lets WebM be encoded frame by frame with WebCodecs too.
  "webm-muxer.mjs": "https://cdn.jsdelivr.net/npm/webm-muxer@5.1.4/build/webm-muxer.mjs",
};

// A current desktop Chrome user agent makes Google serve woff2 with unicode-range subsets.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36";

async function get(url, as = "text") {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  return as === "text" ? res.text() : Buffer.from(await res.arrayBuffer());
}

await rm(fontsDir, { recursive: true, force: true });
await mkdir(fontsDir, { recursive: true });

const css = await get(`https://fonts.googleapis.com/css2?${FONTS.map((f) => `family=${f}`).join("&")}&display=swap`);
const blocks = css.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*{[^}]+}/g) ?? [];
if (!blocks.length) throw new Error("Google Fonts returned no @font-face rules");

const downloaded = new Map();
const out = [];
for (const block of blocks) {
  const fontUrl = block.match(/url\(([^)]+)\)/)[1];
  let name = downloaded.get(fontUrl);
  if (!name) {
    const family = block.match(/font-family:\s*'([^']+)'/)[1].replace(/\s+/g, "");
    name = `${family}-${createHash("sha1").update(fontUrl).digest("hex").slice(0, 10)}.woff2`;
    await writeFile(join(fontsDir, name), await get(fontUrl, "bytes"));
    downloaded.set(fontUrl, name);
  }
  out.push(block.replace(fontUrl, `fonts/${name}`));
}
await writeFile(join(vendor, "fonts.css"), `/* Generated by scripts/vendor.mjs from Google Fonts. */\n${out.join("\n")}\n`);
console.log(`fonts: ${blocks.length} faces, ${downloaded.size} files, ${FONTS.length} families`);

for (const [file, url] of Object.entries(SCRIPTS)) {
  const code = await get(url);
  if (/\bimport\s*[\s{*"'(]/.test(code.replace(/import\.meta/g, ""))) {
    throw new Error(`${file} has imports of its own; vendor them too`);
  }
  await writeFile(join(vendor, file), code);
  console.log(`${file}: ${url} (${code.length} bytes)`);
}
