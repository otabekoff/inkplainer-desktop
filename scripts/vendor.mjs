// Downloads everything Inkplainer would otherwise fetch from the internet at runtime
// (Google Fonts and mp4-muxer) into vendor/, so the desktop app works fully offline.
// Run once (needs internet): `bun run vendor`. The results are meant to be kept.
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const upstream = join(root, "upstream");
const vendor = join(root, "vendor");
const fontsDir = join(vendor, "fonts");

// A current desktop Chrome user agent makes Google serve woff2 with unicode-range subsets.
const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36";

async function get(url, as = "text") {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${res.status} ${res.statusText}: ${url}`);
  return as === "text" ? res.text() : Buffer.from(await res.arrayBuffer());
}

// Every Google Fonts stylesheet the upstream pages link to.
const pages = ["index.html", "pages/docs.html"];
const cssUrls = new Set();
for (const page of pages) {
  const html = await readFile(join(upstream, page), "utf8");
  for (const m of html.matchAll(/href="(https:\/\/fonts\.googleapis\.com\/css2\?[^"]+)"/g)) {
    cssUrls.add(m[1].replaceAll("&amp;", "&"));
  }
}
if (!cssUrls.size) throw new Error("No Google Fonts links found in upstream; has the markup changed?");

await rm(fontsDir, { recursive: true, force: true });
await mkdir(fontsDir, { recursive: true });

// Stylesheets overlap (Caveat and Geist appear more than once); keep each @font-face block once.
const faces = new Map();
for (const url of cssUrls) {
  const css = await get(url);
  for (const block of css.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*{[^}]+}/g) ?? []) {
    const body = block.replace(/\/\*[^*]*\*\/\s*/, "");
    const key = body.replace(/url\([^)]+\)/, "");
    if (!faces.has(key)) faces.set(key, block);
  }
}

let files = 0;
const downloaded = new Map();
const out = [];
for (const block of faces.values()) {
  const fontUrl = block.match(/url\(([^)]+)\)/)[1];
  let name = downloaded.get(fontUrl);
  if (!name) {
    const family = block.match(/font-family:\s*'([^']+)'/)[1].replace(/\s+/g, "");
    name = `${family}-${createHash("sha1").update(fontUrl).digest("hex").slice(0, 10)}.woff2`;
    await writeFile(join(fontsDir, name), await get(fontUrl, "bytes"));
    downloaded.set(fontUrl, name);
    files++;
  }
  out.push(block.replace(fontUrl, `fonts/${name}`));
}
await writeFile(join(vendor, "fonts.css"), `/* Generated by scripts/vendor.mjs from Google Fonts. */\n${out.join("\n")}\n`);
console.log(`fonts: ${faces.size} faces, ${files} files from ${cssUrls.size} stylesheets`);

// mp4-muxer, pinned to the exact version upstream imports.
const html = await readFile(join(upstream, "index.html"), "utf8");
const muxerUrl = html.match(/import\('(https:\/\/cdn\.jsdelivr\.net\/npm\/mp4-muxer@[^']+)'\)/)?.[1];
if (!muxerUrl) throw new Error("mp4-muxer import not found in upstream index.html");
const muxer = await get(muxerUrl);
if (/\bimport\s*[\s{*"'(]/.test(muxer.replace(/import\.meta/g, ""))) {
  throw new Error("mp4-muxer build has imports of its own; vendor them too");
}
await writeFile(join(vendor, "mp4-muxer.mjs"), muxer);
console.log(`mp4-muxer: ${muxerUrl} (${muxer.length} bytes)`);

// webm-muxer (same author and API as mp4-muxer): lets the desktop build encode WebM frame by
// frame with WebCodecs too, instead of recording the screen in real time with MediaRecorder.
const webmUrl = "https://cdn.jsdelivr.net/npm/webm-muxer@5.1.4/build/webm-muxer.mjs";
const webm = await get(webmUrl);
await writeFile(join(vendor, "webm-muxer.mjs"), webm);
console.log(`webm-muxer: ${webmUrl} (${webm.length} bytes)`);
